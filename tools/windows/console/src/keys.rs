/// X11 keysyms to physical US-layout set-2 keys; modifiers remain separate events.
pub fn set2(keysym: u32) -> Option<(u8, bool)> {
    let code = match keysym {
        0x61 | 0x41 => 0x1c,
        0x62 | 0x42 => 0x32,
        0x63 | 0x43 => 0x21,
        0x64 | 0x44 => 0x23,
        0x65 | 0x45 => 0x24,
        0x66 | 0x46 => 0x2b,
        0x67 | 0x47 => 0x34,
        0x68 | 0x48 => 0x33,
        0x69 | 0x49 => 0x43,
        0x6a | 0x4a => 0x3b,
        0x6b | 0x4b => 0x42,
        0x6c | 0x4c => 0x4b,
        0x6d | 0x4d => 0x3a,
        0x6e | 0x4e => 0x31,
        0x6f | 0x4f => 0x44,
        0x70 | 0x50 => 0x4d,
        0x71 | 0x51 => 0x15,
        0x72 | 0x52 => 0x2d,
        0x73 | 0x53 => 0x1b,
        0x74 | 0x54 => 0x2c,
        0x75 | 0x55 => 0x3c,
        0x76 | 0x56 => 0x2a,
        0x77 | 0x57 => 0x1d,
        0x78 | 0x58 => 0x22,
        0x79 | 0x59 => 0x35,
        0x7a | 0x5a => 0x1a,
        0x31 | 0x21 => 0x16,
        0x32 | 0x40 => 0x1e,
        0x33 | 0x23 => 0x26,
        0x34 | 0x24 => 0x25,
        0x35 | 0x25 => 0x2e,
        0x36 | 0x5e => 0x36,
        0x37 | 0x26 => 0x3d,
        0x38 | 0x2a => 0x3e,
        0x39 | 0x28 => 0x46,
        0x30 | 0x29 => 0x45,
        0x2d | 0x5f => 0x4e,
        0x3d | 0x2b => 0x55,
        0x5b | 0x7b => 0x54,
        0x5d | 0x7d => 0x5b,
        0x5c | 0x7c => 0x5d,
        0x3b | 0x3a => 0x4c,
        0x27 | 0x22 => 0x52,
        0x60 | 0x7e => 0x0e,
        0x2c | 0x3c => 0x41,
        0x2e | 0x3e => 0x49,
        0x2f | 0x3f => 0x4a,
        0x20 => 0x29,
        0xff08 => 0x66,
        0xff09 | 0xfe20 => 0x0d,
        0xff0d => 0x5a,
        0xff1b => 0x76,
        0xffe1 => 0x12,
        0xffe2 => 0x59,
        0xffe3 => 0x14,
        0xffe9 | 0xffe7 => 0x11,
        0xffe5 => 0x58,
        0xff7f => 0x77,
        0xff14 => 0x7e,
        0xffbe => 0x05,
        0xffbf => 0x06,
        0xffc0 => 0x04,
        0xffc1 => 0x0c,
        0xffc2 => 0x03,
        0xffc3 => 0x0b,
        0xffc4 => 0x83,
        0xffc5 => 0x0a,
        0xffc6 => 0x01,
        0xffc7 => 0x09,
        0xffc8 => 0x78,
        0xffc9 => 0x07,
        0xffb0 | 0xff9e => 0x70,
        0xffb1 | 0xff9c => 0x69,
        0xffb2 | 0xff99 => 0x72,
        0xffb3 | 0xff9b => 0x7a,
        0xffb4 | 0xff96 => 0x6b,
        0xffb5 | 0xff9d => 0x73,
        0xffb6 | 0xff98 => 0x74,
        0xffb7 | 0xff95 => 0x6c,
        0xffb8 | 0xff97 => 0x75,
        0xffb9 | 0xff9a => 0x7d,
        0xffaa => 0x7c,
        0xffab => 0x79,
        0xffad => 0x7b,
        0xffae | 0xff9f => 0x71,
        0xff13 => return Some((0xe1, false)),
        0xff61 | 0xff15 => return Some((0xe0, false)),
        _ => {
            return Some((
                match keysym {
                    0xffe4 => 0x14,
                    0xffea | 0xffe8 | 0xfe03 => 0x11,
                    0xffeb => 0x1f,
                    0xffec => 0x27,
                    0xff67 => 0x2f,
                    0xffff => 0x71,
                    0xff63 => 0x70,
                    0xff50 => 0x6c,
                    0xff57 => 0x69,
                    0xff51 => 0x6b,
                    0xff52 => 0x75,
                    0xff53 => 0x74,
                    0xff54 => 0x72,
                    0xff55 => 0x7d,
                    0xff56 => 0x7a,
                    0xff8d => 0x5a,
                    0xffaf => 0x4a,
                    _ => return None,
                },
                true,
            ));
        }
    };
    Some((code, false))
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn text_modifiers_navigation_and_special_keys() {
        assert_eq!(set2(u32::from('A')), set2(u32::from('a')));
        assert_eq!(set2(0xffe4), Some((0x14, true)));
        assert_eq!(set2(0xffff), Some((0x71, true)));
        assert_eq!(set2(0xff13), Some((0xe1, false)));
        assert_eq!(set2(0xff61), Some((0xe0, false)));
        assert_eq!(set2(0x10020ac), None);
    }
}
